#include <bits/stdc++.h>
using namespace std;

const int N = 1010;  // 总点数最大值 (左边点 + 右边点 + S + T)
const int INF = 1e9; // 定义一个无穷大，代表刚出发时的无限水流

// ====================================================================
// 【核心结构体：边】
// ====================================================================
struct Edge {
    int to;    // 这条水管通向哪个节点 (目标节点)
    int cap;   // 这条水管【现在还能流多少水】 (残余容量)
    int rev;   // 【神仙指针】：我的反向边在 adj[to] 这个数组里的下标是多少？
};

vector<Edge> adj[N]; // 邻接表存图：adj[u] 存了所有从 u 出发的水管
int d[N];            // 深度数组 (Level Graph)：记录每个点在 BFS 层级图里的深度
int cur[N];          // 【当前弧优化指针】：记录每个点 dfs 遍历到了自己 vector 里的第几条边
int n1, n2, m, S, T; // n1:左边点数, n2:右边点数, m:边数, S:超级源点, T:超级汇点

// ====================================================================
// 【加边函数：成双成对地建边】
// ====================================================================
void add_edge(int u, int v, int cap) {
    // 1. 正向边：从 u 指向 v，初始容量为 cap。
    // 此时它的反向边还没塞进 adj[v]，但下一行马上就要塞进去了！
    // 所以反向边一定在 adj[v] 的末尾，下标也就是 adj[v].size()
    adj[u].push_back({ v, cap, (int)adj[v].size() });

    // 2. 反向边 (反悔边)：从 v 指向 u，初始容量为 0 (水还没流过来，不能往回退)。
    // 它的正向边刚刚已经塞进 adj[u] 了，就是 adj[u] 的最后一个元素
    // 所以正向边的下标就是 adj[u].size() - 1
    adj[v].push_back({ u, 0, (int)adj[u].size() - 1 });
}

// ====================================================================
// 【步骤 1：BFS 建立分层图】
// 目的：给每个点标上深度，水只能从低层(浅)流向高层(深)。
// 这样可以防止水在图里来回绕圈子，保证每次流都是向着终点进发的喵！
// ====================================================================
bool bfs()
{
    memset(d, -1, sizeof d); // 全部初始化为 -1，表示还没被标过深度
    queue<int> q;
    q.push(S); // 把源点 S 丢进队列
    d[S] = 0;  // 源点深度为 0

    while (!q.empty())
    {
        int u = q.front(); q.pop();

        // 遍历从 u 出发的所有管子
        for (auto& e : adj[u]) 
        {
            // 如果对面的点 v 还没被标过深度，且这根管子【还有容量】能过水！
            if (d[e.to] == -1 && e.cap > 0) 
            {
                d[e.to] = d[u] + 1; // 目标点的深度 = 当前深度 + 1
                q.push(e.to);       // 把目标点丢进队列继续搜
            }
        }
    }
    // 如果搜完整个图，发现汇点 T 的深度不是 -1，说明还能走到 T！返回 true！
    return d[T] != -1;
}

// ====================================================================
// 【步骤 2：DFS 寻找增广路 (疯狂找水管向下冲)】
// 参数 u：当前走到的点
// 参数 limit：走到当前点为止，这一路上最窄的管子容量 (木桶效应的短板)
// 返回值：真正流到终点的水量
// ====================================================================
int dfs(int u, int limit) {
    // 如果已经走到终点了，或者路上的水已经被限制榨干了 (limit == 0)
    // 直接把能通的水量返回去！
    if (u == T || limit == 0) return limit;

    int flow = 0; // 记录从 u 这个点，一共成功往外输送了多少水

    // 【当前弧优化】：注意这里是 i = cur[u] 而不是 i = 0！
    // 假设 u 有 10 条边，前 3 条在之前的搜索中已经被彻底榨干了
    // 那么 cur[u] 就会停在 3，下次再来到 u 点时，直接从第 4 条边开始搜！极大地节省时间！
    for (int& i = cur[u]; i < adj[u].size(); i++) {
        Edge& e = adj[u][i]; // 拿到当前遍历的管子

        // 【核心条件】：水只能严格按照深度 d[e.to] == d[u] + 1 往下流！且管子必须有残余容量！
        if (d[e.to] == d[u] + 1 && e.cap > 0) {

            // 递归往下搜，传递给下个点的限制水量是：(目前手里还剩的水) 和 (这根管子的容量) 取最小值
            int t = dfs(e.to, min(limit - flow, e.cap));

            // 如果真的有水流到了终点 (t > 0)
            if (t > 0) {
                e.cap -= t;                      // 正向管子的容量减去流过的水
                adj[e.to][e.rev].cap += t;       // 【反悔机制】：给反向边增加容量！方便以后别的流过来逼着退水

                flow += t;                       // u 点成功送出的总水量增加

                // 如果 u 手里的水已经分发完了 (流出的水 flow == 传过来的水 limit)
                // 直接打断循环，不用再看后面的管子了
                if (flow == limit) break;
            }
        }
    }
    return flow; // 返回 u 点这一波一共送出去多少水
}

// ====================================================================
// 【主引擎：Dinic 算法】
// ====================================================================
int dinic() {
    int max_flow = 0;

    // 只要还能建出从 S 到 T 的分层图 (也就是说，还能找到从起点通向终点的路)
    while (bfs()) {
        // 新的一轮 DFS 开始前，必须把所有点的【当前弧指针】重置为 0
        // 表示这新的一轮，每个点都要重新从它的第一条边开始搜喵！
        memset(cur, 0, sizeof cur);

        // 源点 S 带着无穷大的水 (INF) 开始往下冲！累加冲到终点的水量！
        max_flow += dfs(S, INF);
    }
    return max_flow; // 此时水管网络被彻底榨干，返回的总水量就是二分图最大匹配！
}

int main() {
    // 提速起手式
    ios::sync_with_stdio(0); cin.tie(0);
    cin >> n1 >> n2 >> m;

    S = 0;               // 设定超级源点编号为 0
    T = n1 + n2 + 1;     // 设定超级汇点编号为总点数之和再往后挪一位

    // 1. S 连向所有左半部点，容量为 1 (限制每个左部点只能分配一个对象)
    for (int i = 1; i <= n1; i++) add_edge(S, i, 1);

    // 2. 所有右半部点连向 T，容量为 1 (限制每个右部点只能被分配一次)
    // (注意：为了不和左边点冲突，程序里把右部点的编号平移了 n1，即 n1+1 到 n1+n2)
    for (int i = 1; i <= n2; i++) add_edge(i + n1, T, 1);

    // 3. 原图的左部点连向右部点，容量为 1
    for (int i = 0; i < m; i++) {
        int u, v; cin >> u >> v;
        add_edge(u, v + n1, 1);
    }

    // Dinic 跑出来的最大流，就是咱们要的二分图最大匹配数！
    cout << dinic() << '\n';
    return 0;
}